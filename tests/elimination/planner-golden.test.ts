describe("PLANG core planner equals Tambola 1.9.0", () => {
  test("PLANG1 at least 40 golden budget and count pairs are held", () => expect(GOLDEN.length + EDGE.length).toBeGreaterThanOrEqual(40));
  for (const [t, c, b, cu, bu, total, amounts] of GOLDEN) test(`PLANG2 ${t} ticket(s), ${c} prizes, budget ${b}`, () => {
    const p = planPrizes(t as 1 | 2, c, b);
    expect(p.count).toBe(cu); expect(p.budget).toBe(bu); expect(p.total).toBe(total);
    expect(p.prizes.map((r) => r.amount)).toEqual(amounts);
  });
  EDGE.forEach(([t, c, b, tu, cu, bu, total, amounts], i) => test(`PLANG3 edge input ${i + 1}: ${String(t)}/${String(c)}/${String(b)}`, () => {
    const p = planPrizes(t, c, b);
    expect(p.tickets).toBe(tu); expect(p.count).toBe(cu); expect(p.budget).toBe(bu); expect(p.total).toBe(total);
    expect(p.prizes.map((r) => r.amount)).toEqual(amounts);
  }));
  for (const [k, v] of Object.entries(IDS)) test(`PLANG4 ids and percents of split ${k}`, () => {
    const [t, c] = k.split("/").map(Number) as [1 | 2, number];
    expect(planPrizes(t, c, 1000).prizes.map((r) => r.id + "|" + r.pct)).toEqual(v);
    expect(prizePlanner.split(t, c).map((r) => r.id + "|" + r.pct)).toEqual(v);
  });
  for (const [a, n, want] of SHARES) test(`PLANG5 shareOut(${a}, ${n})`, () => expect(shareOut(a, n)).toEqual(want));
});
